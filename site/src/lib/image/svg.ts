import type { AsciiImageResult } from "ascii-things/image";
import type { StudioOptions } from "./types";

const FONT_SIZE = 12;
const CELL_WIDTH = 7.2;
const LINE_HEIGHT = 12.6;

function escapeText(value: string) {
  return value.replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;");
}

function escapeAttribute(value: string) {
  return escapeText(value).replaceAll('"', "&quot;").replaceAll("'", "&apos;");
}

/**
 * Build a real, text-based SVG. Colour mode becomes one tspan per glyph; large
 * colour fields intentionally trade filesize for editable vector output.
 */
export function buildSvg(
  result: AsciiImageResult,
  options: StudioOptions,
  title = "ASCII art",
): string {
  const safeTitle = escapeText(title);
  const width = Math.ceil(result.columns * CELL_WIDTH);
  const height = Math.ceil(result.rows * LINE_HEIGHT);
  const lines = result.text.split("\n");
  const useColor = options.color && !options.edge;
  const background = options.transparent
    ? ""
    : `\n  <rect width="${width}" height="${height}" fill="${escapeAttribute(options.background)}" />`;

  const rows = lines
    .map((line, row) => {
      const y = (row + 1) * LINE_HEIGHT - 1.8;
      if (!useColor) {
        return `  <text x="0" y="${y}">${escapeText(line)}</text>`;
      }
      const spans = Array.from(line)
        .map((character, column) => {
          const color = result.colors[row * result.columns + column] ?? options.foreground;
          return `<tspan fill="${escapeAttribute(color)}">${escapeText(character)}</tspan>`;
        })
        .join("");
      return `  <text x="0" y="${y}">${spans}</text>`;
    })
    .join("\n");

  return `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}" role="img" aria-label="${escapeAttribute(title)}" xml:space="preserve">
  <title>${safeTitle}</title>
  <desc>${safeTitle}, ${result.columns} columns by ${result.rows} rows, generated by ascii-things.</desc>${background}
  <g fill="${escapeAttribute(options.foreground)}" font-family="Geist Mono, ui-monospace, monospace" font-size="${FONT_SIZE}" font-weight="600" letter-spacing="0">
${rows}
  </g>
</svg>
`;
}
